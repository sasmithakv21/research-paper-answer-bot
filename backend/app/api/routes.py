from fastapi import APIRouter, HTTPException, UploadFile, File, Form, status
from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any
from pathlib import Path

from app.core.config import PAPERS_DIR
from app.rag.chain import ask_question
from app.rag.ingestion import ingest_all_papers, ingest_single_pdf

router = APIRouter(prefix="/api")

# --- Pydantic Schema Models ---

class ChatRequest(BaseModel):
    question: str = Field(..., description="User question about loaded research papers", example="What is multi-head attention?")
    api_key: Optional[str] = Field(None, description="Optional override Gemini API key")

class SourceReference(BaseModel):
    paper: str = Field(..., description="Source PDF filename", example="attention_is_all_you_need.pdf")
    page: int = Field(..., description="1-indexed page number in PDF", example=5)
    snippet: Optional[str] = Field(None, description="Relevant text snippet preview")

class ChatResponse(BaseModel):
    answer: str = Field(..., description="Grounded answer text generated by Gemini")
    sources: List[SourceReference] = Field(..., description="List of paper and page references")

class PaperItem(BaseModel):
    filename: str = Field(..., example="attention_is_all_you_need.pdf")
    name: str = Field(..., example="attention_is_all_you_need.pdf")

class PaperListResponse(BaseModel):
    papers: List[PaperItem]

class UploadResponse(BaseModel):
    status: str = Field(..., example="success")
    filename: str = Field(..., example="resnet_deep_learning.pdf")
    message: str = Field(..., example="Successfully uploaded and indexed 25 chunks from resnet_deep_learning.pdf.")
    chunks_indexed: int = Field(..., example=25)


# --- Endpoint Route Handlers ---

@router.get("/papers", response_model=PaperListResponse, tags=["Papers"], summary="List indexed research papers")
async def list_papers():
    """
    Returns a clean list of available PDF research papers in the backend library 
    for the React frontend sidebar.
    """
    papers_path = Path(PAPERS_DIR)
    if not papers_path.exists():
        return {"papers": []}
    
    pdf_files = [f.name for f in papers_path.glob("*.pdf")]
    papers_list = [{"filename": fname, "name": fname} for fname in pdf_files]
    return {"papers": papers_list}


@router.post("/upload", response_model=UploadResponse, status_code=status.HTTP_200_OK, tags=["Papers"], summary="Upload & index new PDF research paper")
async def upload_paper(file: UploadFile = File(...), api_key: Optional[str] = Form(None)):
    """
    Accepts a PDF file upload, validates file type and size, saves the PDF to disk, 
    and ingests it into ChromaDB vector store using deterministic chunk IDs to prevent duplicates.
    """
    if not file.filename.lower().endswith(".pdf"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, 
            detail="Invalid file format. Only PDF files (.pdf) are supported."
        )
    
    save_path = Path(PAPERS_DIR) / file.filename
    try:
        content = await file.read()
        if not content or len(content) == 0:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST, 
                detail="Uploaded PDF file is empty (0 bytes)."
            )
            
        with open(save_path, "wb") as buffer:
            buffer.write(content)
        
        # Ingest newly uploaded paper into ChromaDB using deterministic chunk IDs
        ingest_res = ingest_single_pdf(str(save_path), api_key=api_key)
        chunks_count = ingest_res.get("chunks_count", 0)
        
        return {
            "status": "success",
            "filename": file.filename,
            "message": f"Successfully uploaded and indexed {chunks_count} chunks from {file.filename}.",
            "chunks_indexed": chunks_count
        }
    except HTTPException:
        raise
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail=f"Failed to process and index PDF file: {str(e)}"
        )


@router.post("/chat", response_model=ChatResponse, tags=["Chat"], summary="Ask a question about research papers")
async def chat_endpoint(request: ChatRequest):
    """
    Accepts a natural language question, retrieves relevant paper passages from ChromaDB, 
    prompts Google Gemini LLM, and returns a grounded answer with page-level source references.
    """
    if not request.question or not request.question.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, 
            detail="Question cannot be empty or whitespace."
        )
    
    try:
        result = ask_question(question=request.question.strip(), api_key=request.api_key)
        return result
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail=f"Error generating answer with Gemini: {str(e)}"
        )


@router.post("/ingest", tags=["Papers"], summary="Re-index all local papers")
async def trigger_ingestion(api_key: Optional[str] = None):
    """Triggers ingestion for all local PDFs in data/papers/."""
    try:
        result = ingest_all_papers(api_key=api_key)
        return result
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, 
            detail=f"Ingestion process failed: {str(e)}"
        )
